// Small DOM, storage and motion helpers shared by every module.

export const $ = (s, el = document) => el.querySelector(s);
export const $$ = (s, el = document) => Array.from(el.querySelectorAll(s));
export const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
export const motionMQ = window.matchMedia('(prefers-reduced-motion: reduce)');
export let reduceMotion = motionMQ.matches;
export function setReduceMotion(v) { reduceMotion = v; }
export const store = {
  get(k) { try { return localStorage.getItem(k); } catch (e) { return null; } },
  set(k, v) { try { localStorage.setItem(k, v); } catch (e) { /* ignore */ } },
};
