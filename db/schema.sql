-- Bloom's PostgreSQL schema (Supabase). Safe to run any number of times:
-- it only creates what is missing and never drops or rewrites data.
-- The server applies it on start-up; migrate_sqlite_to_postgres.py does too.

CREATE TABLE IF NOT EXISTS groups (
    id          TEXT PRIMARY KEY,
    title       TEXT NOT NULL,
    host_name   TEXT NOT NULL,
    start_date  TEXT NOT NULL,
    pw_salt     BYTEA NOT NULL,          -- 16 random bytes
    pw_hash     BYTEA NOT NULL,          -- PBKDF2-SHA256 of the group password
    created_at  BIGINT NOT NULL          -- Unix seconds
);

CREATE TABLE IF NOT EXISTS members (
    id          TEXT PRIMARY KEY,
    -- Insertion order (replaces SQLite's rowid as the tie-breaker when sorting).
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    group_id    TEXT NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    color       TEXT NOT NULL,
    token_hash  TEXT NOT NULL,           -- SHA-256 of the session token, never the token
    avail       JSONB NOT NULL DEFAULT '[]'::jsonb,   -- ["2026-10-20@18", ...]
    votes       JSONB NOT NULL DEFAULT '{}'::jsonb,   -- {"p_abc": 1, ...}
    is_host     BOOLEAN NOT NULL DEFAULT FALSE,
    joined_at   BIGINT NOT NULL,
    updated_at  BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS members_by_group ON members(group_id);
CREATE INDEX IF NOT EXISTS members_by_token ON members(group_id, token_hash);

CREATE TABLE IF NOT EXISTS places (
    id          TEXT PRIMARY KEY,
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    group_id    TEXT NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    kind        TEXT NOT NULL,
    added_by    TEXT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
    created_at  BIGINT NOT NULL,
    details     JSONB                    -- the confirmed place (map, link or typed details)
);
CREATE INDEX IF NOT EXISTS places_by_group ON places(group_id);

-- Supabase exposes the public schema through its REST API. Row level security with
-- no policies means the browser keys (anon/authenticated) can't read or change these
-- tables at all; only the Bloom server's own database login (the table owner) can.
ALTER TABLE groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE members ENABLE ROW LEVEL SECURITY;
ALTER TABLE places ENABLE ROW LEVEL SECURITY;
